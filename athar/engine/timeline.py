"""Builds episodes/<id>.js from a spec (episodes/src/<id>.json) and the measured length of each voice clip.
usage: python3 engine/timeline.py episodes/src/ep02.json durations.json
A spec is a list of beats. Each beat has one voice clip (or a silent `hold`), the on-screen lines and the English
subtitles. Line and subtitle times inside a beat are fractions of the clip (0..1), so the picture follows the voice."""
import json, sys
spec = json.load(open(sys.argv[1], encoding='utf-8')); dur = json.load(open(sys.argv[2]))
t = 0.3; cues = []; subs = []; voice = []; marks = {}
GAP = spec.get('gap', 0.55)
for b in spec['beats']:
    d = dur[str(b['clip'])] if 'clip' in b else b['hold']
    start = t; end = t + d
    marks[b['id']] = (start, end)
    if 'clip' in b: voice.append({'at': round(start, 2), 'clip': b['clip'], 'text': b.get('voice', '')})
    if not b.get('joinPrev'):
        cues.append({'t0': round(start - 0.1, 2), 't1': round(end + 0.3, 2), 'card': bool(b.get('card')), 'lines': []})
    cue = cues[-1]; cue['t1'] = round(end + 0.3, 2)
    for l in b.get('lines', []):
        cue['lines'].append({'at': round(start + l.get('f', 0) * d - cue['t0'], 2), 'cls': l['cls'], 'html': l['html']})
    for s in b.get('subs', []):
        subs.append({'t0': round(start + s.get('f0', 0) * d - (0.1 if s.get('f0', 0) == 0 else 0), 2), 't1': round(start + s.get('f1', 1) * d + (0.3 if s.get('f1', 1) == 1 else 0), 2), 'text': s['text']})
    t = end + b.get('gap', GAP)
total = round(t + spec.get('tail', 1.6), 1)
cues[-1]['t1'] = total + 0.7; subs[-1]['t1'] = total + 0.7
def at(ref):  # "beatId:start+0.2" / "beatId:end-0.3" / "beatId:0.6" (fraction)
    bid, _, pos = ref.partition(':'); s, e = marks[bid]
    if pos.startswith('start'): return round(s + float(pos[5:] or 0), 2)
    if pos.startswith('end'): return round(e + float(pos[3:] or 0), 2)
    return round(s + float(pos) * (e - s), 2)
A = {k: (at(v) if isinstance(v, str) else v) for k, v in spec['action'].items()}
ep = {'id': spec['id'], 'title': spec['title'], 'sources': spec['sources'], 'duration': total, 'brand': {'ar': 'أثَر', 'en': 'ATHAR'},
      'scene': spec.get('scene', {}), 'action': A, 'cues': cues, 'subs': subs, 'voice': voice}
open('episodes/%s.js' % spec['id'], 'w', encoding='utf-8').write(
    '// Generated by engine/timeline.py from episodes/src/%s.json — edit the spec, not this file.\nwindow.EPISODE = %s;\n' % (spec['id'], json.dumps(ep, ensure_ascii=False, indent=1)))
print(spec['id'], 'duration', total, 'action', A, 'voice', [(v['clip'], v['at']) for v in voice])
